import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Turns the captured inner-page HTML into typed modules.
 *
 * Each page exports the inner markup of `<main>` plus its document metadata.
 * The markup is rendered verbatim (minus Astro scoping attributes) so the
 * cloned pages keep the source structure, text and class names.
 */

const root = process.cwd();
const sourceDir = path.join(root, "docs/research/tagmarkets/source/pages");
const outDir = path.join(root, "src/content/tagmarkets/pages");

const pages = [
  "account-types",
  "amplify",
  "deposit-methods",
  "copy-trade",
  "partners",
  "education",
  "contact",
  "risk-warning",
  "privacy",
  "client-agreement",
  "complaints",
  "conflict-of-interest",
  "kyc-aml",
  "refund-and-withdrawal-policy",
  "regulatory-request",
  "insurance",
];

function decodeCfEmail(hex) {
  const key = parseInt(hex.slice(0, 2), 16);
  let out = "";
  for (let i = 2; i < hex.length; i += 2) {
    out += String.fromCharCode(parseInt(hex.slice(i, i + 2), 16) ^ key);
  }
  return out;
}

function transformMain(html) {
  return html
    // Page scripts are reimplemented as React islands; never inject them.
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, "")
    // Astro adds scoping attributes to every element; the clone's stylesheet is
    // generated without those selectors.
    .replace(/\s*data-astro-cid-[a-z0-9]+/g, "")
    // Cloudflare rewrites mailto links to an obfuscated href/span pair. Restore
    // the address but keep the original element structure.
    .replace(
      /href="\/cdn-cgi\/l\/email-protection#([0-9a-f]+)"/g,
      (_match, hex) => `href="mailto:${decodeCfEmail(hex)}"`,
    )
    .replace(
      /<span([^>]*)data-cfemail="([0-9a-f]+)"([^>]*)>[\s\S]*?<\/span>/g,
      (_match, _pre, hex) => `<span class="__cf_email__">${decodeCfEmail(hex)}</span>`,
    )
    .trim();
}

function meta(html, tag, attr = "name") {
  const re = new RegExp(`<meta[^>]*${attr}="${tag}"[^>]*content="([^"]*)"`, "i");
  return html.match(re)?.[1] ?? "";
}

await mkdir(outDir, { recursive: true });

for (const slug of pages) {
  const html = await readFile(path.join(sourceDir, `${slug}.html`), "utf8");
  const start = html.indexOf("<main");
  const end = html.indexOf("</main>");

  if (start === -1 || end === -1) {
    throw new Error(`No <main> in ${slug}.html`);
  }

  const mainHtml = transformMain(html.slice(html.indexOf(">", start) + 1, end));
  const title = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i)?.[1]?.trim() ?? "Tag Markets";
  const description = meta(html, "description");

  const output = `// Generated by scripts/build-page-content.mjs — do not edit by hand.\nexport const title = ${JSON.stringify(title)};\nexport const description = ${JSON.stringify(description)};\nexport const mainHtml = ${JSON.stringify(mainHtml)};\n`;

  await writeFile(path.join(outDir, `${slug}.ts`), output, "utf8");
  console.log(`${slug}.ts — ${mainHtml.length} bytes`);
}
