/**
 * Builds `public/sites/tagmarkets/portal/css/portal.css` — the portal
 * stylesheet bundle, in the same order the portal loads it.
 *
 * The portal routes use their own root layout and link this file directly, so
 * the bytes reach the browser untouched (no bundler re-serialisation).
 *
 * Usage: node scripts/build-portal-css.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import postcss from "postcss";

const root = path.resolve(import.meta.dirname, "..");
const sourceDir = path.join(root, "docs/research/tagmarkets/source/portal-offline");
const outFile = path.join(root, "public/sites/tagmarkets/portal/css/portal.css");

const SOURCES = [
  "bootstrap.min.css",
  "all.min.css",
  "pwstrength-bootstrap.custom.css",
  "jquery-confirm.min.css",
  "style.css",
  "responsive.css",
  "dwf.css",
  "custom.css",
  "base.css",
  "theme-style.css",
  "signup.css",
];

const REWRITES = [
  [/(\.\.\/)+fonts\//g, "/sites/tagmarkets/portal/fonts/"],
  [/(\.\.\/)+webfonts\//g, "/sites/tagmarkets/portal/webfonts/"],
];

const rewritePlugin = {
  postcssPlugin: "rewrite-portal-assets",
  Declaration(decl) {
    if (!decl.value?.includes("url(")) return;
    for (const [pattern, replacement] of REWRITES) {
      decl.value = decl.value.replace(pattern, replacement);
    }
  },
};

const parts = [];
for (const file of SOURCES) {
  const css = await readFile(path.join(sourceDir, file), "utf8");
  parts.push(`/* ${file} */\n${css}`);
}

const banner = `/*
 * Generated by scripts/build-portal-css.mjs — do not edit by hand.
 * Source: portal.tagmarkets.com stylesheets, bundled in source order.
 */
`;

const result = await postcss([rewritePlugin]).process(parts.join("\n"), {
  from: undefined,
});

await writeFile(outFile, banner + result.css, "utf8");
console.log(`wrote ${path.relative(root, outFile)} (${result.css.length} bytes)`);
